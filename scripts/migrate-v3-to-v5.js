#!/usr/bin/env node
/**
 * Strapi v3 → v5 Data Migration Script
 *
 * Reads the old v3 SQLite database and imports all content into the new Strapi v5
 * instance via the REST API (using an admin API token).
 *
 * Prerequisites:
 *   1. The new Strapi v5 instance must be running with all content types defined
 *   2. All uploaded files must already be copied to strapi/public/uploads/
 *   3. An API token must be created in the Strapi admin panel with full access
 *   4. better-sqlite3 is already a Strapi dependency
 *
 * Usage:
 *   STRAPI_TOKEN=<your-api-token> node scripts/migrate-v3-to-v5.js
 */

const Database = require('better-sqlite3');
const path = require('path');
const fs = require('fs');

// ── Configuration ──────────────────────────────────────────────────────────────
const V3_DB_PATH = path.resolve(__dirname, '../strapi-v3-backup/.tmp/data.db');
const STRAPI_URL = process.env.STRAPI_URL || 'http://localhost:3001';
const STRAPI_TOKEN = process.env.STRAPI_TOKEN || '';

// ── Helpers ────────────────────────────────────────────────────────────────────
async function api(method, endpoint, body = null) {
  const url = `${STRAPI_URL}/api${endpoint}`;
  const opts = {
    method,
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${STRAPI_TOKEN}`,
    },
  };
  if (body) opts.body = JSON.stringify(body);

  const res = await fetch(url, opts);
  const text = await res.text();
  let data;
  try { data = JSON.parse(text); } catch { data = text; }

  if (!res.ok) {
    console.error(`API Error ${res.status} ${method} ${endpoint}:`, JSON.stringify(data, null, 2));
    throw new Error(`API ${res.status}: ${method} ${endpoint}`);
  }
  return data;
}

// Upload a single file to Strapi
async function uploadFile(filePath, fileInfo) {
  const FormData = (await import('form-data')).default;
  const form = new FormData();
  form.append('files', fs.createReadStream(filePath), {
    filename: fileInfo.name,
    contentType: fileInfo.mime,
  });
  form.append('fileInfo', JSON.stringify({
    name: fileInfo.name,
    alternativeText: fileInfo.alternativeText || '',
    caption: fileInfo.caption || '',
  }));

  const res = await fetch(`${STRAPI_URL}/api/upload`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${STRAPI_TOKEN}`,
      ...form.getHeaders(),
    },
    body: form,
  });

  if (!res.ok) {
    const errText = await res.text();
    throw new Error(`Upload failed: ${errText}`);
  }
  return await res.json();
}

// ── Open v3 database ───────────────────────────────────────────────────────────
function openV3Database() {
  if (!fs.existsSync(V3_DB_PATH)) {
    throw new Error(`V3 database not found at ${V3_DB_PATH}`);
  }
  return new Database(V3_DB_PATH, { readonly: true });
}

function readTable(db, table) {
  try {
    return db.prepare(`SELECT * FROM "${table}"`).all();
  } catch (e) {
    console.warn(`  ⚠ Table "${table}" not found or empty`);
    return [];
  }
}

function readUploadMorphs(db) {
  return readTable(db, 'upload_file_morph');
}

// ── Phase 1: Migrate uploads ──────────────────────────────────────────────────
async function migrateUploads(db) {
  console.log('\n📁 Migrating upload files...');
  const files = readTable(db, 'upload_file');
  const idMap = {}; // v3 id -> v5 id

  // Only upload original files (skip thumbnails/responsive variants which are
  // auto-generated by Strapi). We identify originals by checking they don't
  // have a name starting with thumbnail_, small_, medium_, large_.
  // Actually, in v3 each row in upload_file IS a unique file (including its
  // formats JSON). So we upload all of them.

  for (const file of files) {
    const fileName = path.basename(file.url);
    const filePath = path.resolve(__dirname, '../strapi/public/uploads', fileName);

    if (!fs.existsSync(filePath)) {
      console.warn(`  ⚠ File not found: ${fileName}, skipping`);
      continue;
    }

    try {
      const uploaded = await uploadFile(filePath, {
        name: file.name,
        mime: file.mime,
        alternativeText: file.alternativeText || '',
        caption: file.caption || '',
      });

      if (Array.isArray(uploaded) && uploaded.length > 0) {
        idMap[file.id] = uploaded[0].id;
        console.log(`  ✓ ${file.name} (v3:${file.id} → v5:${uploaded[0].id})`);
      }
    } catch (e) {
      console.error(`  ✗ Failed to upload ${file.name}: ${e.message}`);
    }
  }

  console.log(`  📊 Migrated ${Object.keys(idMap).length} / ${files.length} files`);
  return idMap;
}

// ── Phase 2: Migrate tags ──────────────────────────────────────────────────────
async function migrateTags(db) {
  console.log('\n🏷️  Migrating tags...');
  const tags = readTable(db, 'tags');
  const idMap = {};

  for (const tag of tags) {
    const res = await api('POST', '/tags', {
      data: {
        name: tag.name || null,
        icon: tag.icon || null,
        title: tag.title || null,
        order: tag.order || null,
      },
    });
    idMap[tag.id] = res.data?.documentId || res.data?.id;
    console.log(`  ✓ Tag: "${tag.name}" (v3:${tag.id} → v5:${idMap[tag.id]})`);
  }

  console.log(`  📊 Migrated ${Object.keys(idMap).length} tags`);
  return idMap;
}

// ── Phase 3: Migrate outlinks ─────────────────────────────────────────────────
async function migrateOutlinks(db) {
  console.log('\n🔗 Migrating outlinks...');
  const outlinks = readTable(db, 'outlinks');
  const idMap = {};

  for (const outlink of outlinks) {
    const res = await api('POST', '/outlinks', {
      data: {
        name: outlink.name || null,
        tooltip: outlink.tooltip || null,
        svg: outlink.svg || null,
      },
    });
    idMap[outlink.id] = res.data?.documentId || res.data?.id;
    console.log(`  ✓ Outlink: "${outlink.name}" (v3:${outlink.id} → v5:${idMap[outlink.id]})`);
  }

  console.log(`  📊 Migrated ${Object.keys(idMap).length} outlinks`);
  return idMap;
}

// ── Phase 4: Migrate categories ───────────────────────────────────────────────
async function migrateCategories(db, uploadIdMap) {
  console.log('\n📂 Migrating categories...');
  const categories = readTable(db, 'categories');
  const morphs = readUploadMorphs(db);
  const idMap = {};

  for (const cat of categories) {
    const catMorphs = morphs.filter(m => m.related_id === cat.id && m.related_type === 'categories');

    const data = {
      name: cat.name || null,
      slug: cat.slug || null,
      description: cat.description || null,
      order: cat.order || null,
      title: cat.title || null,
    };

    const thumbImageMorph = catMorphs.find(m => m.field === 'thumbnailimage');
    if (thumbImageMorph && uploadIdMap[thumbImageMorph.upload_file_id]) {
      data.thumbnailimage = uploadIdMap[thumbImageMorph.upload_file_id];
    }

    const thumbVideoMorph = catMorphs.find(m => m.field === 'thumbnailvideo');
    if (thumbVideoMorph && uploadIdMap[thumbVideoMorph.upload_file_id]) {
      data.thumbnailvideo = uploadIdMap[thumbVideoMorph.upload_file_id];
    }

    const res = await api('POST', '/categories', { data });
    idMap[cat.id] = res.data?.documentId || res.data?.id;
    console.log(`  ✓ Category: "${cat.name}" (v3:${cat.id} → v5:${idMap[cat.id]})`);
  }

  console.log(`  📊 Migrated ${Object.keys(idMap).length} categories`);
  return idMap;
}

// ── Phase 5: Update outlink media ─────────────────────────────────────────────
async function migrateOutlinkMedia(db, outlinkIdMap, uploadIdMap) {
  console.log('\n🔗 Updating outlink media...');
  const morphs = readUploadMorphs(db);
  const outlinks = readTable(db, 'outlinks');

  for (const outlink of outlinks) {
    const outlinkMorphs = morphs.filter(m => m.related_id === outlink.id && m.related_type === 'outlinks');
    const iconMorph = outlinkMorphs.find(m => m.field === 'icon');

    if (iconMorph && uploadIdMap[iconMorph.upload_file_id] && outlinkIdMap[outlink.id]) {
      await api('PUT', `/outlinks/${outlinkIdMap[outlink.id]}`, {
        data: { icon: uploadIdMap[iconMorph.upload_file_id] },
      });
      console.log(`  ✓ Outlink "${outlink.name}" icon updated`);
    }
  }
}

// ── Phase 6: Migrate documents ────────────────────────────────────────────────
async function migrateDocuments(db, uploadIdMap, categoryIdMap, tagIdMap, outlinkIdMap) {
  console.log('\n📄 Migrating documents...');
  const documents = readTable(db, 'documents');
  const morphs = readUploadMorphs(db);
  const idMap = {};

  // Read relation tables
  const docCategories = readTable(db, 'documents__categories');
  const docTags = readTable(db, 'documents__tags');

  // Read component tables
  const contentblocks = readTable(db, 'components_component_contentblocks');
  const beforeafters = readTable(db, 'components_component_beforeafters');
  const moreinfos = readTable(db, 'components_component_moreinfos');

  // Read component link tables
  const docComponents = readTable(db, 'documents_components');

  // Nested component link table
  let cbNestedComponents = [];
  try {
    cbNestedComponents = readTable(db, 'components_component_contentblocks_components');
  } catch { /* may not exist */ }

  for (const doc of documents) {
    const docMorphs = morphs.filter(m => m.related_id === doc.id && m.related_type === 'documents');

    const data = {
      title: doc.title || null,
      description: doc.description || null,
      date: doc.date || null,
      slug: doc.slug || null,
      backgroundcolor: doc.backgroundcolor || null,
      foregroundcolor: doc.foregroundcolor || null,
      foregroundcolor2: doc.foregroundcolor2 || null,
      typeoverride: doc.typeoverride || null,
      order: doc.order || null,
      nopostershadow: doc.nopostershadow === 1 || doc.nopostershadow === true || false,
      shortdescription: doc.shortdescription || null,
      nopage: doc.nopage === 1 || doc.nopage === true || false,
      np_link: doc.np_link || null,
      hero: doc.hero === 1 || doc.hero === true || false,
    };

    // Single media: poster
    const posterMorph = docMorphs.find(m => m.field === 'poster');
    if (posterMorph && uploadIdMap[posterMorph.upload_file_id]) {
      data.poster = uploadIdMap[posterMorph.upload_file_id];
    }

    // Single media: video
    const videoMorph = docMorphs.find(m => m.field === 'video');
    if (videoMorph && uploadIdMap[videoMorph.upload_file_id]) {
      data.video = uploadIdMap[videoMorph.upload_file_id];
    }

    // Multiple media: images
    const imagesMorphs = docMorphs.filter(m => m.field === 'images').sort((a, b) => (a.order || 0) - (b.order || 0));
    if (imagesMorphs.length > 0) {
      data.images = imagesMorphs.map(m => uploadIdMap[m.upload_file_id]).filter(Boolean);
    }

    // Multiple media: laurels
    const laurelMorphs = docMorphs.filter(m => m.field === 'laurels').sort((a, b) => (a.order || 0) - (b.order || 0));
    if (laurelMorphs.length > 0) {
      data.laurels = laurelMorphs.map(m => uploadIdMap[m.upload_file_id]).filter(Boolean);
    }

    // Relations: categories (m2m)
    const catRels = docCategories.filter(r => r.document_id === doc.id);
    if (catRels.length > 0) {
      data.categories = catRels.map(r => categoryIdMap[r.category_id]).filter(Boolean);
    }

    // Relations: tags (m2m)
    const tagRels = docTags.filter(r => r.document_id === doc.id);
    if (tagRels.length > 0) {
      data.tags = tagRels.map(r => tagIdMap[r.tag_id]).filter(Boolean);
    }

    // Relation: single category
    if (doc.category && categoryIdMap[doc.category]) {
      data.category = categoryIdMap[doc.category];
    }

    // Components: contentblocks
    const docCBLinks = docComponents.filter(
      l => l.document_id === doc.id && l.component_type === 'components_component_contentblocks'
    );
    if (docCBLinks.length > 0) {
      data.contentblocks = docCBLinks
        .sort((a, b) => (a.order || 0) - (b.order || 0))
        .map(link => {
          const cb = contentblocks.find(c => c.id === link.component_id);
          if (!cb) return null;

          const cbData = {
            title: cb.title || null,
            description: cb.description || null,
            videoembed: cb.videoembed || null,
            videoembedaspect: cb.videoembedaspect || null,
            squarestills: cb.squarestills === 1 || cb.squarestills === true || false,
          };

          // Tag relation
          if (cb.tag && tagIdMap[cb.tag]) {
            cbData.tag = tagIdMap[cb.tag];
          }

          // Stills (multiple media)
          const cbMorphs = morphs.filter(
            m => m.related_id === cb.id &&
              m.related_type === 'components_component_contentblocks' &&
              m.field === 'stills'
          ).sort((a, b) => (a.order || 0) - (b.order || 0));
          if (cbMorphs.length > 0) {
            cbData.stills = cbMorphs.map(m => uploadIdMap[m.upload_file_id]).filter(Boolean);
          }

          // Nested beforeafters
          const baLinks = cbNestedComponents.filter(
            l => l.components_component_contentblock_id === cb.id &&
              l.component_type === 'components_component_beforeafters'
          );
          if (baLinks.length > 0) {
            cbData.beforeafters = baLinks
              .sort((a, b) => (a.order || 0) - (b.order || 0))
              .map(baLink => {
                const ba = beforeafters.find(b => b.id === baLink.component_id);
                if (!ba) return null;

                const baData = {
                  caption: ba.caption || null,
                  offset: ba.offset != null ? ba.offset : 0.5,
                };

                const baMorphs = morphs.filter(
                  m => m.related_id === ba.id && m.related_type === 'components_component_beforeafters'
                );
                const beforeMorph = baMorphs.find(m => m.field === 'before');
                if (beforeMorph && uploadIdMap[beforeMorph.upload_file_id]) {
                  baData.before = uploadIdMap[beforeMorph.upload_file_id];
                }
                const afterMorph = baMorphs.find(m => m.field === 'after');
                if (afterMorph && uploadIdMap[afterMorph.upload_file_id]) {
                  baData.after = uploadIdMap[afterMorph.upload_file_id];
                }

                return baData;
              })
              .filter(Boolean);
          }

          return cbData;
        })
        .filter(Boolean);
    }

    // Components: moreinfo
    const docMILinks = docComponents.filter(
      l => l.document_id === doc.id && l.component_type === 'components_component_moreinfos'
    );
    if (docMILinks.length > 0) {
      data.moreinfo = docMILinks
        .sort((a, b) => (a.order || 0) - (b.order || 0))
        .map(link => {
          const mi = moreinfos.find(m => m.id === link.component_id);
          if (!mi) return null;

          const miData = {
            header: mi.header || null,
            subheader: mi.subheader || null,
            link: mi.link || null,
          };

          if (mi.outlink && outlinkIdMap[mi.outlink]) {
            miData.outlink = outlinkIdMap[mi.outlink];
          }

          return miData;
        })
        .filter(Boolean);
    }

    try {
      const res = await api('POST', '/documents', { data });
      idMap[doc.id] = res.data?.documentId || res.data?.id;
      console.log(`  ✓ Document: "${doc.title}" (v3:${doc.id} → v5:${idMap[doc.id]})`);
    } catch (e) {
      console.error(`  ✗ Failed to migrate document "${doc.title}": ${e.message}`);
    }
  }

  console.log(`  📊 Migrated ${Object.keys(idMap).length} / ${documents.length} documents`);
  return idMap;
}

// ── Phase 7: Migrate home (single type) ───────────────────────────────────────
async function migrateHome(db, uploadIdMap, documentIdMap) {
  console.log('\n🏠 Migrating home...');
  const homes = readTable(db, 'homes');
  if (homes.length === 0) {
    console.log('  ⚠ No home data found');
    return;
  }

  const home = homes[0];
  const morphs = readUploadMorphs(db);
  const homeMorphs = morphs.filter(m => m.related_id === home.id && m.related_type === 'homes');

  const data = {
    description: home.description || null,
    subtitle: home.subtitle || null,
    underconstruction: home.underconstruction === 1 || home.underconstruction === true || false,
    metadescription: home.metadescription || null,
  };

  // metaimage
  const metaimageMorph = homeMorphs.find(m => m.field === 'metaimage');
  if (metaimageMorph && uploadIdMap[metaimageMorph.upload_file_id]) {
    data.metaimage = uploadIdMap[metaimageMorph.upload_file_id];
  }

  // Featured documents (one-to-many)
  // Try different possible table names for the join table
  let homeDocLinks = readTable(db, 'homes__featured');
  if (homeDocLinks.length === 0) {
    homeDocLinks = readTable(db, 'homes_featured__documents');
  }
  if (homeDocLinks.length > 0) {
    data.featured = homeDocLinks
      .map(l => documentIdMap[l.document_id] || documentIdMap[l.featured_id])
      .filter(Boolean);
  }

  // Random images component
  const homeComponents = readTable(db, 'homes_components');
  const randomImages = readTable(db, 'components_component_random_images');

  const riLinks = homeComponents.filter(
    l => l.home_id === home.id && l.component_type === 'components_component_random_images'
  );

  if (riLinks.length > 0) {
    data.images = riLinks
      .sort((a, b) => (a.order || 0) - (b.order || 0))
      .map(link => {
        const ri = randomImages.find(r => r.id === link.component_id);
        if (!ri) return null;

        const riData = {
          caption: ri.caption || null,
        };

        if (ri.document && documentIdMap[ri.document]) {
          riData.document = documentIdMap[ri.document];
        }

        const riMorphs = morphs.filter(
          m => m.related_id === ri.id &&
            m.related_type === 'components_component_random_images' &&
            m.field === 'image'
        );
        if (riMorphs.length > 0 && uploadIdMap[riMorphs[0].upload_file_id]) {
          riData.image = uploadIdMap[riMorphs[0].upload_file_id];
        }

        return riData;
      })
      .filter(Boolean);
  }

  await api('PUT', '/home', { data });
  console.log(`  ✓ Home migrated`);
}

// ── Phase 8: Migrate contact-image (single type) ─────────────────────────────
async function migrateContactImage(db, uploadIdMap) {
  console.log('\n📸 Migrating contact-image...');
  const contactImages = readTable(db, 'contact_images');
  if (contactImages.length === 0) {
    console.log('  ⚠ No contact-image data found');
    return;
  }

  const ci = contactImages[0];
  const morphs = readUploadMorphs(db);
  const ciMorphs = morphs.filter(m => m.related_id === ci.id && m.related_type === 'contact_images');

  const data = {};

  const imageMorphs = ciMorphs.filter(m => m.field === 'image').sort((a, b) => (a.order || 0) - (b.order || 0));
  if (imageMorphs.length > 0) {
    data.image = imageMorphs.map(m => uploadIdMap[m.upload_file_id]).filter(Boolean);
  }

  await api('PUT', '/contact-image', { data });
  console.log(`  ✓ Contact-image migrated`);
}

// ── Main ───────────────────────────────────────────────────────────────────────
async function main() {
  console.log('🚀 Strapi v3 → v5 Data Migration');
  console.log(`   Source DB: ${V3_DB_PATH}`);
  console.log(`   Target:    ${STRAPI_URL}`);
  console.log('');

  if (!STRAPI_TOKEN) {
    console.error('❌ STRAPI_TOKEN environment variable is required.');
    console.error('   Create a full-access API token in Strapi admin → Settings → API Tokens');
    process.exit(1);
  }

  const db = openV3Database();

  // List all tables for debugging
  const tables = db.prepare("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name").all();
  console.log('📋 V3 database tables:', tables.map(t => t.name).join(', '));

  // Execute migration in dependency order
  const uploadIdMap = await migrateUploads(db);
  const tagIdMap = await migrateTags(db);
  const outlinkIdMap = await migrateOutlinks(db);
  const categoryIdMap = await migrateCategories(db, uploadIdMap);
  await migrateOutlinkMedia(db, outlinkIdMap, uploadIdMap);
  const documentIdMap = await migrateDocuments(db, uploadIdMap, categoryIdMap, tagIdMap, outlinkIdMap);
  await migrateHome(db, uploadIdMap, documentIdMap);
  await migrateContactImage(db, uploadIdMap);

  db.close();

  console.log('\n✅ Migration complete!');
  console.log('   Next steps:');
  console.log('   1. Verify data in Strapi admin panel');
  console.log('   2. Test GraphQL queries from the Nuxt frontend');
  console.log('   3. Run "npm run generate" in nuxt/ to test static generation');
}

main().catch(err => {
  console.error('💥 Migration failed:', err);
  process.exit(1);
});
